-- LegalEdu Manager — private file storage
-- Bucket is PRIVATE: no public URLs. Access only through these policies and
-- short-lived signed URLs created by the server after authorization.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'academic-files',
  'academic-files',
  false,
  52428800, -- 50 MB hard ceiling; the app enforces MAX_UPLOAD_MB (default 20)
  array[
    'application/pdf',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.openxmlformats-officedocument.presentationml.presentation',
    'text/plain'
  ]
)
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

-- Owner of a submission folder, bypassing RLS (NULL when the submission does not exist yet).
create or replace function public.storage_submission_owner(object_name text) returns uuid
language sql stable security definer set search_path = public as $$
  select s.student_id from public.submissions s
  where s.id::text = split_part(object_name, '/', 2)
$$;

create or replace function public.student_can_read_material_object(object_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.teaching_materials m
    where m.storage_key = object_name and m.visible_to_students and (
      (m.assignment_id is not null and public.student_can_see_assignment(m.assignment_id))
      or m.subject_id in (select sg.subject_id from public.subject_groups sg where sg.group_id in (select public.student_group_ids()))
    )
  )
$$;

revoke all on function public.storage_submission_owner(text), public.student_can_read_material_object(text) from public;
grant execute on function public.storage_submission_owner(text), public.student_can_read_material_object(text) to authenticated;

-- Staff: full access to the bucket.
create policy "academic-files staff all" on storage.objects for all to authenticated
  using (bucket_id = 'academic-files' and public.is_staff())
  with check (bucket_id = 'academic-files' and public.is_staff());

-- Students: read objects of their own submissions.
create policy "academic-files student read own submissions" on storage.objects for select to authenticated
  using (
    bucket_id = 'academic-files'
    and split_part(name, '/', 1) = 'submissions'
    and public.storage_submission_owner(name) = public.current_student_id()
  );

-- Students: upload into a submission folder that is theirs or not yet created
-- (the folder id is a fresh random UUID generated by the server).
create policy "academic-files student upload" on storage.objects for insert to authenticated
  with check (
    bucket_id = 'academic-files'
    and split_part(name, '/', 1) = 'submissions'
    and public.current_student_id() is not null
    and coalesce(public.storage_submission_owner(name), public.current_student_id()) = public.current_student_id()
  );

-- Students: remove only orphaned objects they uploaded themselves (cleanup after a failed upload).
create policy "academic-files student cleanup" on storage.objects for delete to authenticated
  using (
    bucket_id = 'academic-files'
    and owner_id = auth.uid()::text
    and split_part(name, '/', 1) = 'submissions'
    and public.storage_submission_owner(name) is null
  );

-- Students: read visible teaching materials of their subjects/assignments.
create policy "academic-files student read materials" on storage.objects for select to authenticated
  using (
    bucket_id = 'academic-files'
    and split_part(name, '/', 1) = 'materials'
    and public.student_can_read_material_object(name)
  );
